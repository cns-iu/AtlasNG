import { AnalyticsEventCategory } from '@atlasng/analytics/events';
import { AnalyticsPermissionedStorageKeys } from '@atlasng/analytics/permissions';

/**
 * Key under which the `analytics` package reads and writes the anonymous ID.
 */
export const ANONYMOUS_ID_KEY = '__anon_id';

/**
 * Storage key used to keep the anonymous ID once `statistics` consent is granted.
 */
export const ANONYMOUS_ID_STORAGE_KEY = '__atlasng_analytics_anon_id__';

/**
 * Generates a random anonymous ID.
 * Uses `crypto.getRandomValues`, which, unlike `crypto.randomUUID`, also works outside secure contexts.
 *
 * @returns A 32 character hexadecimal ID
 */
export function generateAnonymousId(): string {
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  return Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('');
}

/**
 * Registers the anonymous ID with the permissioned storage.
 * The ID is generated by the storage, so the `an_aid` URL parameter can't replace it,
 * and it is persisted only once the user grants the `statistics` category.
 */
export const ANONYMOUS_ID_STORAGE_KEYS: AnalyticsPermissionedStorageKeys = {
  [ANONYMOUS_ID_KEY]: {
    key: ANONYMOUS_ID_STORAGE_KEY,
    category: AnalyticsEventCategory.Statistics,
    generate: generateAnonymousId,
  },
};
