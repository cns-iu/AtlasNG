import { DOCUMENT, LocationStrategy } from '@angular/common';
import { HttpClient } from '@angular/common/http';
import { computed, inject, Service, signal } from '@angular/core';
import { LinkHandler } from '@atlasng/common';
import { AngError } from '@atlasng/core';
import { DesignSystemErrorCode } from '@atlasng/design-system/errors';
import { firstValueFrom } from 'rxjs';

/** Matches a date-only ISO 8601 string such as `2026-06-16`. */
const DATE_ONLY_PATTERN = /^(\d{4})-(\d{2})-(\d{2})$/;

/**
 * Last modified dates of the application's routes, read by `ang-last-modified` for the current route.
 *
 * Load the JSON file generated by the `@atlasng/nx-plugin:last-modified-dates` executor with {@link loadFromUrl},
 * or set dates directly with {@link set}.
 */
@Service()
export class LastModifiedDates {
  /** Client used to load dates files. */
  readonly #http = inject(HttpClient);

  /** Document whose base URL the current URL is resolved against. */
  readonly #document = inject(DOCUMENT);

  /** Strategy providing the application base href. */
  readonly #locationStrategy = inject(LocationStrategy);

  /** Current URL. Query and fragment changes are ignored since they don't change the route. */
  readonly #url = inject(LinkHandler).currentUrl({ queryParams: false, fragment: false });

  /** Current route, normalized for lookups. */
  readonly #route = computed(() => normalizeRoute(this.#toPath(this.#url())));

  /** Dates keyed by normalized route. Replaced on every change so that readers are notified. */
  readonly #dates = signal(new Map<string, Date>());

  /** Last modified date of the current route, or `undefined` when it has none. */
  readonly current = computed(() => this.get(this.#route()));

  /**
   * Gets the last modified date of a route.
   *
   * @param route Route or path, for example `/dataset/heart`. The query, fragment, and trailing slash are ignored.
   * @returns The date, or `undefined` when the route has none.
   */
  get(route: string): Date | undefined {
    return this.#dates().get(normalizeRoute(route));
  }

  /**
   * Sets the last modified date of a route, replacing any earlier date.
   *
   * @param route Route or path, for example `/dataset/heart`. The query, fragment, and trailing slash are ignored.
   * @param date The date.
   * @throws {AngError} When the date is invalid.
   */
  set(route: string, date: Date): void {
    if (Number.isNaN(date.getTime())) {
      throw new AngError(
        DesignSystemErrorCode.InvalidLastModifiedDate,
        (typeof ngDevMode === 'undefined' || ngDevMode) && `Invalid last modified date for route ${route}.`,
      );
    }

    this.#dates.update((dates) => new Map(dates).set(normalizeRoute(route), date));
  }

  /**
   * Loads dates from a JSON file that maps routes to dates, for example `{ "/dataset/heart": 1781568000000 }`,
   * and merges them into the existing dates. Values may be timestamps in milliseconds or ISO 8601 strings;
   * invalid values are skipped.
   *
   * @param url URL of the file. Relative URLs resolve against the document base URL.
   * @returns A promise that resolves once the dates are set, or rejects when the file can't be loaded.
   */
  async loadFromUrl(url: string): Promise<void> {
    const data = await firstValueFrom(this.#http.get<unknown>(url));
    if (typeof data !== 'object' || data === null) {
      return;
    }

    this.#dates.update((dates) => {
      const next = new Map(dates);
      for (const [route, value] of Object.entries(data)) {
        const date = parseDate(value);
        if (date) {
          next.set(normalizeRoute(route), date);
        }
      }
      return next;
    });
  }

  /**
   * Converts a link handler URL to an application path relative to the application base href.
   *
   * @param url Absolute or root-relative URL, for example `https://example.com/app/dataset/heart;v=2`.
   * @returns The path with its matrix parameters, for example `dataset/heart;v=2` for the base `/app/`.
   */
  #toPath(url: string): string {
    const { baseURI } = this.#document;
    const { pathname } = new URL(url, baseURI);
    const basePath = new URL(this.#locationStrategy.getBaseHref(), baseURI).pathname.replace(/\/?$/, '/');
    return pathname.startsWith(basePath) ? pathname.slice(basePath.length) : pathname;
  }
}

/**
 * Parses a date. Date-only ISO 8601 strings such as `2026-06-16` are read as local dates, as `DatePipe` does.
 *
 * @param value A `Date`, a timestamp in milliseconds, or an ISO 8601 string.
 * @returns The date, or `undefined` when the value is missing or can't be parsed.
 */
export function parseDate(value: unknown): Date | undefined {
  let date: Date;
  if (value instanceof Date) {
    date = value;
  } else if (typeof value === 'number') {
    date = new Date(value);
  } else if (typeof value === 'string' && value.trim() !== '') {
    const match = DATE_ONLY_PATTERN.exec(value.trim());
    date = match ? new Date(Number(match[1]), Number(match[2]) - 1, Number(match[3])) : new Date(value);
  } else {
    return undefined;
  }

  return Number.isNaN(date.getTime()) ? undefined : date;
}

/**
 * Normalizes a path to a route by dropping the query, fragment, and trailing slash.
 *
 * @param path Path, for example `/dataset/heart/?tab=1#files`.
 * @returns The route, for example `/dataset/heart`.
 */
function normalizeRoute(path: string): string {
  const route = path.split(/[?#]/, 1)[0].replace(/^\/+|\/+$/g, '');
  return `/${route}`;
}
