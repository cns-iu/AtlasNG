import { type ExecutorContext, logger } from '@nx/devkit';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import generateTypographyScssExecutor, {
  buildScss,
  parseTypescale,
  parseTypography,
  parseWeight,
  toRem,
  toScssString,
  toVariableFontName,
  type Typography,
} from './executor.ts';

const FONT_TOKENS = {
  Static: {
    Font: {
      Brand: { $type: 'string', $value: 'Metropolis' },
      Plain: { $type: 'string', $value: 'Nunito Sans' },
    },
    Weight: {
      Regular: { $type: 'string', $value: 'Regular' },
      'Semi_bold Italic': { $type: 'string', $value: 'Semi-Bold Italic' },
      Bold: {},
    },
  },
};

const style = (font: string, weight: string, extra: Record<string, unknown> = {}) => ({
  Font: { $value: font },
  Weight: { $value: weight },
  Size: { $value: 16 },
  'Line height': { $value: 24 },
  Tracking: { $value: 0.5 },
  ...extra,
});

const TYPESCALE_TOKENS = {
  Static: {
    'Title large': style('Metropolis', 'Bold'),
    'Body large': style('Nunito Sans', 'Regular'),
    'Label large': style('Nunito Sans', 'Medium', { 'Weight-emphasized': { $value: 'Bold' } }),
    'Body small': style('Nunito Sans', 'Regular', { 'Weight-emphasized': { $value: 'Bold' } }),
    Custom: style('Nunito Sans', 'Regular'),
    Incomplete: { Font: { $value: 'Nunito Sans' } },
    Scalar: 1,
  },
};

describe('generate-typography-scss executor', () => {
  let root: string;
  let context: ExecutorContext;

  const writeTokens = (font: unknown, typescale: unknown) => {
    mkdirSync(join(root, 'themes/cns'), { recursive: true });
    writeFileSync(join(root, 'themes/cns/font.tokens.json'), JSON.stringify(font));
    writeFileSync(join(root, 'themes/cns/typescale.tokens.json'), JSON.stringify(typescale));
  };

  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'generate-typography-scss-'));
    context = {
      root,
      cwd: root,
      isVerbose: false,
      projectName: 'themes',
      targetName: 'generate-typography-scss',
      configurationName: 'cns',
    } as ExecutorContext;
    vi.spyOn(logger, 'info').mockImplementation(() => undefined);
    vi.spyOn(logger, 'error').mockImplementation(() => undefined);
  });

  afterEach(() => {
    rmSync(root, { recursive: true, force: true });
    vi.restoreAllMocks();
  });

  it('writes the typography maps to the output file', async () => {
    writeTokens(FONT_TOKENS, TYPESCALE_TOKENS);

    const result = await generateTypographyScssExecutor(
      {
        input: 'themes/cns/font.tokens.json',
        typescale: 'themes/cns/typescale.tokens.json',
        output: 'themes/cns/_typography.scss',
        plainVariable: true,
      },
      context,
    );

    expect(result).toEqual({ success: true });
    expect(readFileSync(join(root, 'themes/cns/_typography.scss'), 'utf8')).toMatchInlineSnapshot(`
      "// This file was generated by running 'npx nx run themes:generate-typography-scss:cns'.
      // Proceed with caution if making changes to this file.

      // Note: Typography tokens are generated from 'themes/cns/font.tokens.json'
      $typography: (
        plain-family: 'Nunito Sans Variable',
        brand-family: Metropolis,
        regular-weight: 400,
        semi-bold-weight: 600,
        bold-weight: 700,
      );

      // Note: Typography overrides are generated from 'themes/cns/typescale.tokens.json'
      $typography-overrides: (
        body-large: 400 1rem #{'/'} 1.5rem 'Nunito Sans Variable',
        body-large-font: 'Nunito Sans Variable',
        body-large-line-height: 1.5rem,
        body-large-size: 1rem,
        body-large-tracking: 0.031rem,
        body-large-weight: 400,
        body-small: 400 1rem #{'/'} 1.5rem 'Nunito Sans Variable',
        body-small-font: 'Nunito Sans Variable',
        body-small-line-height: 1.5rem,
        body-small-size: 1rem,
        body-small-tracking: 0.031rem,
        body-small-weight: 400,
        label-large: 500 1rem #{'/'} 1.5rem 'Nunito Sans Variable',
        label-large-font: 'Nunito Sans Variable',
        label-large-line-height: 1.5rem,
        label-large-size: 1rem,
        label-large-tracking: 0.031rem,
        label-large-weight: 500,
        label-large-weight-prominent: 700,
        title-large: 700 1rem #{'/'} 1.5rem Metropolis,
        title-large-font: Metropolis,
        title-large-line-height: 1.5rem,
        title-large-size: 1rem,
        title-large-tracking: 0.031rem,
        title-large-weight: 700,
      );
      "
    `);
    expect(logger.info).toHaveBeenCalledWith('Wrote themes/cns/_typography.scss');
  });

  it('writes next to the input without an output', async () => {
    writeTokens(FONT_TOKENS, TYPESCALE_TOKENS);

    const result = await generateTypographyScssExecutor(
      { input: 'themes/cns/font.tokens.json', typescale: 'themes/cns/typescale.tokens.json' },
      context,
    );

    expect(result).toEqual({ success: true });
    expect(existsSync(join(root, 'themes/cns/font.typography.scss'))).toBe(true);
  });

  it('fails for invalid tokens', async () => {
    writeTokens({ Static: {} }, TYPESCALE_TOKENS);

    const result = await generateTypographyScssExecutor(
      { input: 'themes/cns/font.tokens.json', typescale: 'themes/cns/typescale.tokens.json' },
      context,
    );

    expect(result).toEqual({ success: false });
    expect(logger.error).toHaveBeenCalledWith('Missing required token: Static.Font.Plain.$value');
  });

  describe('parseTypography', () => {
    it('reads families and weights', () => {
      expect(parseTypography(FONT_TOKENS)).toEqual({
        plainFamily: 'Nunito Sans',
        brandFamily: 'Metropolis',
        weights: { regular: 400, 'semi-bold': 600, bold: 700 },
      });
    });

    it('uses variable font names when requested', () => {
      expect(parseTypography(FONT_TOKENS, { plainVariable: true, brandVariable: true })).toMatchObject({
        plainFamily: 'Nunito Sans Variable',
        brandFamily: 'Metropolis Variable',
      });
    });

    it.each([
      [{}, 'Missing required token: Static.Font.Plain.$value'],
      [{ Static: { Font: { Plain: { $value: ' ' } } } }, 'Missing required token: Static.Font.Plain.$value'],
      [{ Static: { Font: { Plain: { $value: 'A' } } } }, 'Missing required token: Static.Font.Brand.$value'],
      [{ Static: { Font: { Plain: { $value: 'A' }, Brand: { $value: 'B' } } } }, 'Static.Weight'],
      [
        { Static: { Font: { Plain: { $value: 'A' }, Brand: { $value: 'B' } }, Weight: { X: { $value: 'Chunky' } } } },
        'Unsupported typography weight name: Chunky',
      ],
      [
        { Static: { Font: { Plain: { $value: 'A' }, Brand: { $value: 'B' } }, Weight: { Chunky: null } } },
        'Unsupported typography weight name: Chunky',
      ],
    ])('rejects %o', (tokens, message) => {
      expect(() => parseTypography(tokens)).toThrow(message);
    });
  });

  describe('parseTypescale', () => {
    const typography: Typography = { plainFamily: 'Nunito Sans', brandFamily: 'Metropolis Variable', weights: {} };

    it('orders Material styles and skips other entries', () => {
      expect(parseTypescale(TYPESCALE_TOKENS, typography).map((s) => s.name)).toEqual([
        'body-large',
        'body-small',
        'label-large',
        'title-large',
      ]);
    });

    it('resolves variable font names per family option', () => {
      const tokens = {
        Static: { 'Body large': style('Nunito Sans', 'Regular'), 'Title large': style('Metropolis', 'Bold') },
      };

      expect(parseTypescale(tokens, typography).map((s) => s.font)).toEqual(['Nunito Sans', 'Metropolis']);
      expect(parseTypescale(tokens, typography, { brandVariable: true }).map((s) => s.font)).toEqual([
        'Nunito Sans',
        'Metropolis Variable',
      ]);
    });

    it.each([
      [{}, 'Missing required token group: Static'],
      [{ Static: {} }, 'No valid typescale styles'],
      [{ Static: { Custom: style('A', 'Regular') } }, 'No Material typescale styles'],
      [{ Static: { 'Body large': style('A', 'Chunky') } }, 'Unsupported typography weight name in typescale: Chunky'],
      [
        { Static: { 'Body large': style('A', 'Regular', { 'Weight-emphasized': { $value: 'Chunky' } }) } },
        'Unsupported typography emphasized weight name in typescale: Chunky',
      ],
    ])('rejects %o', (tokens, message) => {
      expect(() => parseTypescale(tokens, typography)).toThrow(message);
    });
  });

  it.each([
    ['Regular', 'x', 400],
    ['', 'Extra-Light', 200],
    [undefined, 'Black Italic', 900],
    ['Chunky', 'x', undefined],
  ])('parses weight %o (fallback %s) as %o', (value, fallback, expected) => {
    expect(parseWeight(value, fallback)).toBe(expected);
  });

  it.each([
    ['Metropolis', 'Metropolis'],
    ['Nunito Sans', "'Nunito Sans'"],
    ["O'Brien\\Sans", "'O\\'Brien\\\\Sans'"],
  ])('formats %s as SCSS %s', (value, expected) => {
    expect(toScssString(value)).toBe(expected);
  });

  it.each([
    [16, '1rem'],
    [0, '0rem'],
    [0.5, '0.031rem'],
    [-4, '-0.25rem'],
    [20, '1.25rem'],
  ])('converts %dpx to %s', (value, expected) => {
    expect(toRem(value)).toBe(expected);
  });

  it.each([
    [' Roboto ', 'Roboto Variable'],
    ['Roboto variable', 'Roboto variable'],
  ])('makes %o a variable font name', (value, expected) => {
    expect(toVariableFontName(value)).toBe(expected);
  });

  it('builds empty maps', () => {
    expect(buildScss('a.json', 'b.json', ['// banner'], { plainFamily: 'A', brandFamily: 'B', weights: {} }, []))
      .toMatchInlineSnapshot(`
      "// banner

      // Note: Typography tokens are generated from 'a.json'
      $typography: (
        plain-family: A,
        brand-family: B,
      );

      // Note: Typography overrides are generated from 'b.json'
      $typography-overrides: (
      );
      "
    `);
  });
});
