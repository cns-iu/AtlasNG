import { type ExecutorContext, logger } from '@nx/devkit';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import generatePalettesScssExecutor, {
  buildScss,
  buildValidationSpecs,
  findKey,
  normalizeKey,
  parseCorePalettes,
  parseExtPalettes,
  readPalettes,
  validatePalettes,
} from './executor.ts';

const TONES = [0, 10, 20, 25, 30, 35, 40, 50, 60, 70, 80, 90, 95, 98, 99, 100];
const NEUTRAL_TONES = [...TONES, 4, 6, 12, 17, 22, 24, 87, 92, 94, 96];

const token = (hex: string) => ({ $type: 'color', $value: { hex } });

const nested = (tones: number[], hex: string) => Object.fromEntries(tones.map((tone) => [String(tone), token(hex)]));

const flat = (name: string, tones: number[], hex: string) =>
  Object.fromEntries(tones.map((tone) => [`${name} ${tone}`, token(hex)]));

const PALETTES = {
  $description: 'metadata',
  Primary: nested(TONES, '#AA0000'),
  ...flat('Secondary', TONES, '#00aa00'),
  tertiary: nested(TONES, '#0000aa'),
  Neutral: nested(NEUTRAL_TONES, '#111111'),
  ...flat('Neutral_Variant', TONES, '#222222'),
  Error: nested(TONES, '#ff0000'),
  'Unknown 10': token('#123456'),
  NoTone: token('#123456'),
  Ext: {
    $type: 'color',
    note: 'not a palette',
    Warning: nested([10, 20, 30, 40, 80, 90, 100], '#ffaa00'),
    Success: {
      ...nested([100, 10, 20, 30, 40, 80, 90, 95], '#00ff00'),
      label: token('#000000'),
      Variant: nested([80, 30], '#00cc00'),
    },
  },
};

const coreBlock = (name: string, tones: number[], hex: string) =>
  [`  ${name}: (`, ...tones.map((tone) => `    ${tone}: ${hex},`), '  ),'].join('\n');

const EXPECTED = `// This file was generated by running 'npx nx run themes:generate-palettes-scss:cns'.
// Proceed with caution if making changes to this file.

@use 'sass:map';

// Note: Color palettes are generated from 'themes/cns/palette.tokens.json'
$_palettes: (
${coreBlock('primary', TONES, '#aa0000')}
${coreBlock('secondary', TONES, '#00aa00')}
${coreBlock('tertiary', TONES, '#0000aa')}
${coreBlock('neutral', NEUTRAL_TONES, '#111111')}
${coreBlock('neutral-variant', TONES, '#222222')}
${coreBlock('error', TONES, '#ff0000')}
);

$_rest: (
  secondary: map.get($_palettes, secondary),
  neutral: map.get($_palettes, neutral),
  neutral-variant: map.get($_palettes, neutral-variant),
  error: map.get($_palettes, error),
);

$primary-palette: map.merge(map.get($_palettes, primary), $_rest);
$tertiary-palette: map.merge(map.get($_palettes, tertiary), $_rest);

$ext-palettes: (
  success: (
    10: #00ff00,
    20: #00ff00,
    30: #00ff00,
    40: #00ff00,
    80: #00ff00,
    90: #00ff00,
    95: #00ff00,
    100: #00ff00,
    variant: (
      30: #00cc00,
      80: #00cc00,
    ),
  ),
  warning: (
    10: #ffaa00,
    20: #ffaa00,
    30: #ffaa00,
    40: #ffaa00,
    80: #ffaa00,
    90: #ffaa00,
    100: #ffaa00,
  ),
);
`;

describe('generate-palettes-scss executor', () => {
  let root: string;
  let context: ExecutorContext;

  const writeTokens = (tokens: unknown) => {
    mkdirSync(join(root, 'themes/cns'), { recursive: true });
    writeFileSync(join(root, 'themes/cns/palette.tokens.json'), JSON.stringify(tokens));
  };

  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'generate-palettes-scss-'));
    context = {
      root,
      cwd: root,
      isVerbose: false,
      projectName: 'themes',
      targetName: 'generate-palettes-scss',
      configurationName: 'cns',
    } as ExecutorContext;
    vi.spyOn(logger, 'info').mockImplementation(() => undefined);
    vi.spyOn(logger, 'error').mockImplementation(() => undefined);
  });

  afterEach(() => {
    rmSync(root, { recursive: true, force: true });
    vi.restoreAllMocks();
  });

  it('writes the palettes to the output file', async () => {
    writeTokens({ palettes: PALETTES });

    const result = await generatePalettesScssExecutor(
      { input: 'themes/cns/palette.tokens.json', output: 'themes/cns/_palettes.scss' },
      context,
    );

    expect(result).toEqual({ success: true });
    expect(readFileSync(join(root, 'themes/cns/_palettes.scss'), 'utf8')).toBe(EXPECTED);
    expect(logger.info).toHaveBeenCalledWith('Wrote themes/cns/_palettes.scss');
  });

  it('writes next to the input without an output', async () => {
    writeTokens({ Palettes: PALETTES });

    const result = await generatePalettesScssExecutor({ input: 'themes/cns/palette.tokens.json' }, context);

    expect(result).toEqual({ success: true });
    expect(existsSync(join(root, 'themes/cns/palette.palettes.scss'))).toBe(true);
  });

  it('fails for incomplete palettes', async () => {
    writeTokens({ palettes: { Primary: { '0': token('#000000') } } });

    const result = await generatePalettesScssExecutor({ input: 'themes/cns/palette.tokens.json' }, context);

    expect(result).toEqual({ success: false });
    expect(logger.error).toHaveBeenCalledWith(expect.stringContaining('Missing palette entries ('));
  });

  it.each([
    ['Neutral Variant', 'neutral-variant'],
    ['  Neutral__variant ', 'neutral-variant'],
    ['ERROR', 'error'],
  ])('normalizes %o to %o', (key, expected) => {
    expect(normalizeKey(key)).toBe(expected);
  });

  describe('findKey', () => {
    it.each([null, undefined, 'text'])('returns undefined for %o', (object) => {
      expect(findKey(object, 'ext')).toBeUndefined();
    });

    it('matches keys ignoring case and separators but skips metadata', () => {
      expect(findKey({ $ext: 1, 'EXT ': 2 }, 'ext')).toBe(2);
      expect(findKey({ $ext: 1 }, 'ext')).toBeUndefined();
    });
  });

  describe('readPalettes', () => {
    it.each([{}, { palettes: 'x' }, { palettes: null }])('rejects %o', (tokens) => {
      expect(() => readPalettes(tokens)).toThrow('Input file must contain a "palettes" object (case-insensitive).');
    });
  });

  describe('parseCorePalettes', () => {
    it('reads flat and nested tones, skipping unknown palettes and keys without tones', () => {
      expect(
        parseCorePalettes({
          'Primary-40': token('#ABCDEF'),
          Secondary: { '10': token('#000000'), '20': { $value: {} } },
          Custom: { '10': token('#000000') },
          Plain: token('#000000'),
        }),
      ).toEqual({ primary: { 40: '#abcdef' }, secondary: { 10: '#000000', 20: undefined } });
    });
  });

  describe('parseExtPalettes', () => {
    it.each([{}, { ext: 'x' }, { ext: {} }, { ext: { $type: 'color', note: 'x', empty: null } }])(
      'returns null for %o',
      (palettes) => {
        expect(parseExtPalettes(palettes)).toBeNull();
      },
    );

    it('collects sorted tones and an optional variant', () => {
      expect(
        parseExtPalettes({
          ext: {
            Info_Blue: { '20': token('#BBBBBB'), ' 10 ': token('#aaaaaa'), variant: 'x' },
            alert: { '10': null, variant: { '80': token('#cccccc') } },
          },
        }),
      ).toEqual({
        alert: { tones: { 10: undefined }, variant: { 80: '#cccccc' } },
        'info-blue': { tones: { 10: '#aaaaaa', 20: '#bbbbbb' }, variant: null },
      });
    });
  });

  describe('validatePalettes', () => {
    it('accepts complete palettes', () => {
      const palettes = readPalettes({ palettes: PALETTES });
      const specs = buildValidationSpecs(parseCorePalettes(palettes), parseExtPalettes(palettes));

      expect(specs.map(({ label }) => label)).toContain('ext success variant');
      expect(() => validatePalettes(specs)).not.toThrow();
    });

    it('reports missing and invalid tones', () => {
      const specs = buildValidationSpecs(
        { primary: { 0: '#000', 10: undefined } },
        { brand: { tones: { 5: 'red', 10: '#000000' }, variant: { 30: '#000000' } } },
      );

      expect(() => validatePalettes(specs)).toThrow(
        /^Missing palette entries \(\d+\): primary 20, .*ext brand 20, .*ext brand variant 80\nInvalid hex color entries \(3\): primary 0, primary 10, ext brand 5$/,
      );
    });

    it('reports only invalid tones', () => {
      expect(() => validatePalettes([{ label: 'ext x', palette: { 1: '#00000g' }, tones: [] }])).toThrow(
        /^Invalid hex color entries \(1\): ext x 1$/,
      );
    });
  });

  it('builds the file without extension palettes', () => {
    const scss = buildScss('// banner', 'in.json', {}, null);

    expect(scss).toMatch(
      /^\/\/ banner\n\n@use 'sass:map';\n\n\/\/ Note: Color palettes are generated from 'in.json'\n/,
    );
    expect(scss).toContain('    0: undefined,');
    expect(scss).not.toContain('$ext-palettes');
    expect(scss.endsWith('$tertiary-palette: map.merge(map.get($_palettes, tertiary), $_rest);\n')).toBe(true);
  });
});
