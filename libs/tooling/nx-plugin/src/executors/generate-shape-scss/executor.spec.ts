import { type ExecutorContext, logger } from '@nx/devkit';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import generateShapeScssExecutor, { buildScss, parseShapes, toCornerValue } from './executor.ts';

const TOKENS = {
  Corner: {
    small: { $type: 'number', $value: 8 },
    none: { $type: 'number', $value: 0 },
    'large-top': { $type: 'number', $value: 16 },
    'large-start': { $type: 'number', $value: 16 },
    'large-end': { $type: 'number', $value: 16 },
    unknown: { $type: 'number', $value: 3 },
  },
};

describe('generate-shape-scss executor', () => {
  let root: string;
  let context: ExecutorContext;

  const writeTokens = (tokens: unknown) => {
    mkdirSync(join(root, 'themes/cns'), { recursive: true });
    writeFileSync(join(root, 'themes/cns/shape.tokens.json'), JSON.stringify(tokens));
  };

  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'generate-shape-scss-'));
    context = {
      root,
      cwd: root,
      isVerbose: false,
      projectName: 'themes',
      targetName: 'generate-shape-scss',
      configurationName: 'cns',
    } as ExecutorContext;
    vi.spyOn(logger, 'info').mockImplementation(() => undefined);
    vi.spyOn(logger, 'error').mockImplementation(() => undefined);
  });

  afterEach(() => {
    rmSync(root, { recursive: true, force: true });
    vi.restoreAllMocks();
  });

  it('writes the shape overrides to the output file', async () => {
    writeTokens(TOKENS);

    const result = await generateShapeScssExecutor(
      { input: 'themes/cns/shape.tokens.json', output: 'themes/cns/_shape.scss' },
      context,
    );

    expect(result).toEqual({ success: true });
    expect(readFileSync(join(root, 'themes/cns/_shape.scss'), 'utf8')).toMatchInlineSnapshot(`
      "// This file was generated by running 'npx nx run themes:generate-shape-scss:cns'.
      // Proceed with caution if making changes to this file.

      // Note: Shape overrides are generated from 'themes/cns/shape.tokens.json'
      $shape-overrides: (
        corner-large-end: 0 16px 16px 0,
        corner-large-start: 16px 0 0 16px,
        corner-large-top: 16px 16px 0 0,
        corner-none: 0,
        corner-small: 8px,
      );
      "
    `);
    expect(logger.info).toHaveBeenCalledWith('Wrote themes/cns/_shape.scss');
  });

  it('writes next to the input without an output', async () => {
    writeTokens(TOKENS);

    const result = await generateShapeScssExecutor({ input: 'themes/cns/shape.tokens.json' }, context);

    expect(result).toEqual({ success: true });
    expect(existsSync(join(root, 'themes/cns/shape.shape.scss'))).toBe(true);
  });

  it('fails for invalid tokens', async () => {
    writeTokens({ Corner: { small: { $value: '8' } } });

    const result = await generateShapeScssExecutor({ input: 'themes/cns/shape.tokens.json' }, context);

    expect(result).toEqual({ success: false });
    expect(logger.error).toHaveBeenCalledWith('Missing or invalid Corner.small.$value (expected a number).');
  });

  describe('parseShapes', () => {
    it('requires a Corner object', () => {
      expect(() => parseShapes({})).toThrow('Input file must contain a "Corner" object.');
    });

    it.each([{}, { $value: Number.NaN }, null])('rejects the token %o', (token) => {
      expect(() => parseShapes({ Corner: { full: token } })).toThrow('Corner.full.$value');
    });

    it('keeps only supported keys', () => {
      expect(parseShapes(TOKENS)).toEqual({ small: 8, none: 0, 'large-top': 16, 'large-start': 16, 'large-end': 16 });
    });
  });

  it.each([
    ['small', 4, '4px'],
    ['none', 0, '0'],
    ['small-top', 4, '4px 4px 0 0'],
    ['small-bottom', 4, '0 0 4px 4px'],
    ['small-start', 4, '4px 0 0 4px'],
    ['small-end', 4, '0 4px 4px 0'],
  ])('formats %s=%d as %s', (key, value, expected) => {
    expect(toCornerValue(key, value)).toBe(expected);
  });

  it('builds an empty map', () => {
    expect(buildScss('// banner', 'in.json', {})).toMatchInlineSnapshot(`
      "// banner

      // Note: Shape overrides are generated from 'in.json'
      $shape-overrides: (
      );
      "
    `);
  });
});
