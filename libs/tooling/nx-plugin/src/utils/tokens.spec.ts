import { type ExecutorContext } from '@nx/devkit';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import {
  createScssBanner,
  findKey,
  getHex,
  getNumberToken,
  getTokenValue,
  isJsonObject,
  normalizeKey,
  readTokensFile,
} from './tokens.ts';

describe('tokens utils', () => {
  describe('isJsonObject', () => {
    it('accepts plain objects', () => {
      expect(isJsonObject({})).toBe(true);
    });

    it.each([null, undefined, 'text', 1, [], [{}]])('rejects %o', (value) => {
      expect(isJsonObject(value)).toBe(false);
    });
  });

  describe('getTokenValue', () => {
    it('reads $value', () => {
      expect(getTokenValue({ $value: 'x' })).toBe('x');
    });

    it.each([null, undefined, 'text', [{ $value: 'x' }]])('returns undefined for %o', (token) => {
      expect(getTokenValue(token)).toBeUndefined();
    });
  });

  describe('readTokensFile', () => {
    let root: string;

    beforeEach(() => {
      root = mkdtempSync(join(tmpdir(), 'tokens-utils-'));
    });

    afterEach(() => {
      rmSync(root, { recursive: true, force: true });
    });

    it('parses a JSON object', async () => {
      writeFileSync(join(root, 'a.json'), '{"Corner":{}}');

      await expect(readTokensFile(join(root, 'a.json'))).resolves.toEqual({ Corner: {} });
    });

    it('rejects non-object JSON', async () => {
      writeFileSync(join(root, 'a.json'), 'null');

      await expect(readTokensFile(join(root, 'a.json'))).rejects.toThrow('Input file must contain a JSON object.');
    });
  });

  describe('getNumberToken', () => {
    it('reads a numeric $value', () => {
      expect(getNumberToken({ small: { $value: 8 } }, 'small', 'Corner')).toBe(8);
    });

    it.each([undefined, null, {}, { $value: '8' }, { $value: Number.POSITIVE_INFINITY }])(
      'rejects the token %o',
      (token) => {
        expect(() => getNumberToken({ small: token }, 'small', 'Shape.Corner')).toThrow(
          'Missing or invalid Shape.Corner.small.$value (expected a number).',
        );
      },
    );
  });

  describe('createScssBanner', () => {
    it('names the target and configuration', () => {
      const context = { projectName: 'lib', targetName: 'gen', configurationName: 'cns' } as ExecutorContext;

      expect(createScssBanner(context)).toEqual([
        "// This file was generated by running 'npx nx run lib:gen:cns'.",
        '// Proceed with caution if making changes to this file.',
      ]);
    });

    it('omits a missing configuration', () => {
      const context = { projectName: 'lib', targetName: 'gen' } as ExecutorContext;

      expect(createScssBanner(context)[0]).toContain("'npx nx run lib:gen'");
    });
  });

  describe('normalizeKey', () => {
    it.each([
      ['Neutral Variant', 'neutral-variant'],
      ['  Neutral__variant ', 'neutral-variant'],
      ['ERROR', 'error'],
    ])('normalizes %o to %o', (key, expected) => {
      expect(normalizeKey(key)).toBe(expected);
    });
  });

  describe('findKey', () => {
    it.each([null, undefined, 'text', ['ext']])('returns undefined for %o', (object) => {
      expect(findKey(object, 'ext')).toBeUndefined();
    });

    it('matches keys ignoring case and separators but skips metadata', () => {
      expect(findKey({ $ext: 1, 'EXT ': 2 }, 'ext')).toBe(2);
      expect(findKey({ $ext: 1 }, 'ext')).toBeUndefined();
    });
  });

  describe('getHex', () => {
    it('reads the lowercased hex color', () => {
      expect(getHex({ $value: { hex: '#ABCDEF' } })).toBe('#abcdef');
    });

    it.each([null, undefined, {}, { $value: { hex: 1 } }])('returns undefined for %o', (token) => {
      expect(getHex(token)).toBeUndefined();
    });
  });
});
