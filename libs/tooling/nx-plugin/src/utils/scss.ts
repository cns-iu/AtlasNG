import { type ExecutorContext, logger } from '@nx/devkit';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, format, resolve } from 'node:path';

/** Indentation used for nested entries in generated SCSS maps. */
export const SCSS_INDENT = '  ';

/** A parsed tokens JSON file. */
export type TokensObject = Record<string, unknown>;

/** Result returned by the SCSS generator executors. */
export interface ExecutorResult {
  /** Whether the executor finished without errors. */
  success: boolean;
}

/**
 * Reads and parses a tokens JSON file exported from Figma.
 *
 * @param inputPath Absolute path to the tokens JSON file.
 * @returns The parsed tokens object.
 * @throws If the file does not contain a JSON object.
 */
export async function readTokensFile(inputPath: string): Promise<TokensObject> {
  const tokens: unknown = JSON.parse(await readFile(inputPath, 'utf8'));
  if (!tokens || typeof tokens !== 'object') {
    throw new Error('Input file must contain a JSON object.');
  }

  return tokens as TokensObject;
}

/**
 * Resolves the absolute path of a generated SCSS file.
 * Without an explicit output the file is placed next to the input, replacing its
 * `.tokens.json`/`.json` extension with `extension`, e.g. `shape.tokens.json` => `shape.shape.scss`.
 *
 * @param root The workspace root that relative paths are resolved against.
 * @param input Path to the tokens JSON file.
 * @param output Optional explicit output path.
 * @param extension Extension of the default output file, e.g. `.shape.scss`.
 * @returns The absolute output path.
 */
export function resolveOutputPath(root: string, input: string, output: string | undefined, extension: string): string {
  if (output) {
    return resolve(root, output);
  }

  const inputPath = resolve(root, input);
  return format({
    dir: dirname(inputPath),
    name: basename(inputPath).replace(/(\.tokens)?\.json$/i, ''),
    ext: extension,
  });
}

/**
 * Builds the header comment of a generated SCSS file, naming the Nx target that regenerates it.
 *
 * @param context The Nx executor context.
 * @returns The two banner lines, without a trailing newline.
 */
export function createScssBanner(context: ExecutorContext): string {
  const target = [context.projectName, context.targetName, context.configurationName].filter(Boolean).join(':');
  return [
    `// This file was generated by running 'npx nx run ${target}'.`,
    '// Proceed with caution if making changes to this file.',
  ].join('\n');
}

/**
 * Writes a generated SCSS file, creating its directory when needed.
 *
 * @param outputPath Absolute path of the file to write.
 * @param content The SCSS source.
 */
export async function writeScssFile(outputPath: string, content: string): Promise<void> {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, content, 'utf8');
}

/**
 * Runs an executor task, logging any error instead of throwing it.
 *
 * @param task The work to run.
 * @returns `{ success: true }` when the task resolves, otherwise `{ success: false }`.
 */
export async function runExecutorTask(task: () => Promise<void>): Promise<ExecutorResult> {
  try {
    await task();
    return { success: true };
  } catch (error) {
    logger.error(error instanceof Error ? error.message : String(error));
    return { success: false };
  }
}
