import { type ExecutorContext, logger } from '@nx/devkit';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { createScssBanner, readTokensFile, resolveOutputPath, runExecutorTask, writeScssFile } from './scss.ts';

describe('scss utils', () => {
  let root: string;

  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'figma-scss-utils-'));
    vi.spyOn(logger, 'error').mockImplementation(() => undefined);
  });

  afterEach(() => {
    rmSync(root, { recursive: true, force: true });
    vi.restoreAllMocks();
  });

  describe('readTokensFile', () => {
    it('parses a JSON object', async () => {
      writeFileSync(join(root, 'a.json'), '{"Corner":{}}');

      await expect(readTokensFile(join(root, 'a.json'))).resolves.toEqual({ Corner: {} });
    });

    it('rejects non-object JSON', async () => {
      writeFileSync(join(root, 'a.json'), 'null');

      await expect(readTokensFile(join(root, 'a.json'))).rejects.toThrow('Input file must contain a JSON object.');
    });
  });

  describe('resolveOutputPath', () => {
    it('resolves an explicit output against the root', () => {
      expect(resolveOutputPath('/ws', 'in/shape.tokens.json', 'out/_shape.scss', '.shape.scss')).toBe(
        '/ws/out/_shape.scss',
      );
    });

    it.each([
      ['in/shape.tokens.json', '/ws/in/shape.shape.scss'],
      ['in/Shape.JSON', '/ws/in/Shape.shape.scss'],
    ])('derives the output from %s', (input, expected) => {
      expect(resolveOutputPath('/ws', input, undefined, '.shape.scss')).toBe(expected);
    });
  });

  describe('createScssBanner', () => {
    it('names the target and configuration', () => {
      const context = { projectName: 'lib', targetName: 'gen', configurationName: 'cns' } as ExecutorContext;

      expect(createScssBanner(context)).toBe(
        "// This file was generated by running 'npx nx run lib:gen:cns'.\n" +
          '// Proceed with caution if making changes to this file.',
      );
    });

    it('omits a missing configuration', () => {
      const context = { projectName: 'lib', targetName: 'gen' } as ExecutorContext;

      expect(createScssBanner(context)).toContain("'npx nx run lib:gen'");
    });
  });

  it('writes a file and creates its directory', async () => {
    const outputPath = join(root, 'nested/dir/out.scss');

    await writeScssFile(outputPath, '$a: 1;\n');

    expect(readFileSync(outputPath, 'utf8')).toBe('$a: 1;\n');
  });

  describe('runExecutorTask', () => {
    it('succeeds when the task resolves', async () => {
      await expect(runExecutorTask(async () => undefined)).resolves.toEqual({ success: true });
    });

    it.each([new Error('boom'), 'boom'])('logs and fails when the task throws %s', async (error) => {
      const result = await runExecutorTask(async () => {
        throw error;
      });

      expect(result).toEqual({ success: false });
      expect(logger.error).toHaveBeenCalledWith('boom');
    });
  });
});
