import { type ExecutorContext } from '@nx/devkit';
import { readFile } from 'node:fs/promises';
import { type OutputData } from './output.ts';

/** A parsed tokens JSON file. */
export type TokensObject = Record<string, unknown>;

/**
 * Asserts that a value is a plain JSON object, not `null` or an array.
 *
 * @param value The value to check.
 * @param message The error message thrown when the check fails.
 * @throws If `value` is not a JSON object.
 */
export function assertJsonObject(value: unknown, message: string): asserts value is Record<string, unknown> {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(message);
  }
}

/**
 * Reads a token's numeric `$value`.
 *
 * @param group The token group containing the token.
 * @param key The token key.
 * @param path Path of the group within the tokens file, used in the error message, e.g. `Corner`.
 * @returns The token value.
 * @throws If the value is not a finite number.
 */
export function getNumberToken(group: Record<string, unknown>, key: string, path: string): number {
  const value = (group[key] as { $value?: unknown } | undefined)?.$value;
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    throw new Error(`Missing or invalid ${path}.${key}.$value (expected a number).`);
  }

  return value;
}

/**
 * Reads and parses a tokens JSON file exported from Figma.
 *
 * @param inputPath Absolute path to the tokens JSON file.
 * @returns The parsed tokens object.
 * @throws If the file does not contain a JSON object.
 */
export async function readTokensFile(inputPath: string): Promise<TokensObject> {
  const tokens: unknown = JSON.parse(await readFile(inputPath, 'utf8'));
  assertJsonObject(tokens, 'Input file must contain a JSON object.');

  return tokens;
}

/**
 * Builds the header comment of a generated SCSS file, naming the Nx target that regenerates it.
 *
 * @param context The Nx executor context.
 * @returns The two banner lines.
 */
export function createScssBanner(context: ExecutorContext): OutputData {
  const target = [context.projectName, context.targetName, context.configurationName].filter(Boolean).join(':');
  return [
    `// This file was generated by running 'npx nx run ${target}'.`,
    '// Proceed with caution if making changes to this file.',
  ];
}
