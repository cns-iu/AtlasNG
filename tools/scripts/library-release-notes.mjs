#!/usr/bin/env node

import fs from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';

const LIBRARIES_GROUP = 'libraries';
const VERSION_BUMP_ONLY_PATTERN = /^This was a version bump only/m;

/**
 * Maps every Nx project name in the workspace to its root directory.
 *
 * @returns {Promise<Map<string, string>>} Project names mapped to their roots.
 */
async function getProjectRoots() {
  const roots = new Map();
  for await (const file of fs.glob('libs/**/project.json', { exclude: (name) => name === 'node_modules' })) {
    const { name } = JSON.parse(await fs.readFile(file, 'utf8'));
    roots.set(name, path.dirname(file));
  }

  return roots;
}

/**
 * Extracts the body of a version's section from a changelog generated by `nx release`.
 *
 * @param {string} changelog The changelog contents.
 * @param {string} version The version whose section is extracted, without a `v` prefix.
 * @returns {string | undefined} The section body without its heading, or `undefined` if the version is missing.
 */
function extractVersionSection(changelog, version) {
  const sections = changelog.split(/^(?=## )/m);
  const section = sections.find((candidate) => candidate.startsWith(`## ${version} `));
  return section?.slice(section.indexOf('\n') + 1).trim();
}

/**
 * Builds combined release notes for the fixed `libraries` release group from each library's changelog.
 * Libraries whose section only records a version bump are left out.
 *
 * @param {string} version The released version, with or without a `v` prefix.
 * @returns {Promise<string>} The release notes as Markdown.
 */
async function buildReleaseNotes(version) {
  const nxJson = JSON.parse(await fs.readFile('nx.json', 'utf8'));
  const projects = nxJson.release.groups[LIBRARIES_GROUP].projects;
  const roots = await getProjectRoots();
  const notes = [];

  for (const project of projects) {
    const root = roots.get(project);
    if (!root) {
      throw new Error(`Unable to find the root of release project "${project}"`);
    }

    const { name } = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'));
    const changelog = await fs.readFile(path.join(root, 'CHANGELOG.md'), 'utf8').catch(() => '');
    const section = extractVersionSection(changelog, version.replace(/^v/, ''));
    if (section && !VERSION_BUMP_ONLY_PATTERN.test(section)) {
      notes.push(`## ${name}\n\n${section.replace(/^### /gm, '#### ')}`);
    }
  }

  return notes.length > 0 ? notes.join('\n\n') + '\n' : 'This was a version bump only, there were no code changes.\n';
}

const { positionals } = parseArgs({ allowPositionals: true });
if (positionals.length !== 1) {
  console.error('Usage: node tools/scripts/library-release-notes.mjs <version>');
  process.exit(1);
}

process.stdout.write(await buildReleaseNotes(positionals[0]));
