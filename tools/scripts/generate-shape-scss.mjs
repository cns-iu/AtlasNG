#!/usr/bin/env node

import { Command } from 'commander';
import fs from 'node:fs/promises';
import path from 'node:path';

const INDENT = '  ';
const SCSS_BANNER = `// This file was generated by running 'node tools/scripts/generate-shape-scss.mjs'.
// Proceed with caution if making changes to this file.`;
const SHAPE_KEYS = [
  'extra-large',
  'extra-large-top',
  'extra-small',
  'extra-small-top',
  'full',
  'large',
  'large-end',
  'large-start',
  'large-top',
  'medium',
  'none',
  'small',
];

function resolveOutputPath(inputPath, options) {
  if (options.output) {
    return path.resolve(options.output);
  }

  return path.format({
    dir: path.dirname(inputPath),
    name: path.basename(inputPath).replace(/(\.tokens)?\.json$/i, ''),
    ext: '.shape.scss',
  });
}

async function readTokens(inputPath) {
  const raw = await fs.readFile(inputPath, 'utf8');
  const tokens = JSON.parse(raw);

  if (!tokens || typeof tokens !== 'object') {
    throw new Error('Input file must contain a JSON object.');
  }

  const corner = tokens.Corner;
  if (!corner || typeof corner !== 'object') {
    throw new Error('Input file must contain a "Corner" object.');
  }

  return tokens;
}

function getNumberToken(cornerTokens, key) {
  const token = cornerTokens[key];
  const value = token?.$value;

  if (typeof value !== 'number' || !Number.isFinite(value)) {
    throw new Error(`Missing or invalid Corner.${key}.$value (expected a number).`);
  }

  return value;
}

function parseShapes(tokens) {
  const corner = tokens.Corner;
  const shapes = {};

  for (const key of SHAPE_KEYS) {
    if (!(key in corner)) {
      continue;
    }

    shapes[key] = getNumberToken(corner, key);
  }

  return shapes;
}

function toPx(value) {
  return value === 0 ? '0' : `${value}px`;
}

function toCornerValue(key, value) {
  if (key.endsWith('-top')) {
    return `${toPx(value)} ${toPx(value)} 0 0`;
  }

  if (key.endsWith('-bottom')) {
    return `0 0 ${toPx(value)} ${toPx(value)}`;
  }

  if (key.endsWith('-start')) {
    return `${toPx(value)} 0 0 ${toPx(value)}`;
  }

  if (key.endsWith('-end')) {
    return `0 ${toPx(value)} ${toPx(value)} 0`;
  }

  return toPx(value);
}

function shapeToScssMap(shape) {
  const lines = [];
  lines.push('(');

  for (const key of SHAPE_KEYS) {
    if (!(key in shape)) {
      continue;
    }

    lines.push(`${INDENT}corner-${key}: ${toCornerValue(key, shape[key])},`);
  }

  lines.push(')');
  return lines.join('\n');
}

function buildScss(input, shape) {
  const shapeMap = shapeToScssMap(shape);

  return [
    SCSS_BANNER,
    '',
    `// Note: Shape overrides are generated from '${input}'`,
    `$shape-overrides: ${shapeMap};`,
    '',
  ].join('\n');
}

async function run(input, options) {
  const inputPath = path.resolve(input);
  const outputPath = resolveOutputPath(inputPath, options);
  const tokens = await readTokens(inputPath);
  const shape = parseShapes(tokens);
  const scss = buildScss(input, shape);

  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, scss, 'utf8');
}

async function main() {
  const program = new Command()
    .name('generate-shape-scss')
    .description('Generate shape SCSS from a shape tokens JSON file.')
    .argument('<input>', 'Path to the source shape tokens JSON file')
    .option('-o, --output <file>', 'Path to the output SCSS file')
    .action(run);

  try {
    await program.parseAsync();
  } catch (error) {
    // eslint-disable-next-line no-console
    console.error(`Error: ${error.message}`);
    process.exit(1);
  }
}

await main();
