#!/usr/bin/env node

import { Command } from 'commander';
import fs from 'node:fs/promises';
import path from 'node:path';

const INDENT = '  ';
const SCSS_BANNER = `// This file was generated by running 'node tools/scripts/generate-typography-scss.mjs'.
// Proceed with caution if making changes to this file.`;
const DEFAULT_REM_DECIMALS = 3;
const VARIABLE_FONT_SUFFIX = ' Variable';
const MATERIAL_TYPESCALE_STYLE_ORDER = [
  'body-large',
  'body-medium',
  'body-small',
  'display-large',
  'display-medium',
  'display-small',
  'headline-large',
  'headline-medium',
  'headline-small',
  'label-large',
  'label-medium',
  'label-small',
  'title-large',
  'title-medium',
  'title-small',
];
const PROMINENT_WIEGHT_TYPESCALES = ['label-large', 'label-medium'];

// MDN common font weight name mapping:
// https://developer.mozilla.org/en-US/docs/Web/CSS/font-weight#common_weight_name_mapping
const TYPOGRAPHY_WEIGHT_BY_NAME = {
  thin: 100,
  hairline: 100,
  'extra light': 200,
  'ultra light': 200,
  light: 300,
  regular: 400,
  normal: 400,
  medium: 500,
  'semi bold': 600,
  semibold: 600,
  demibold: 600,
  bold: 700,
  'extra bold': 800,
  'ultra bold': 800,
  black: 900,
  heavy: 900,
};

function resolveOutputPath(inputPath, options) {
  if (options.output) {
    return path.resolve(options.output);
  }

  return path.format({
    dir: path.dirname(inputPath),
    name: path.basename(inputPath).replace(/(\.tokens)?\.json$/i, ''),
    ext: '.typography.scss',
  });
}

async function readTokens(inputPath) {
  const raw = await fs.readFile(inputPath, 'utf8');
  const tokens = JSON.parse(raw);

  if (!tokens || typeof tokens !== 'object') {
    throw new Error('Input file must contain a JSON object.');
  }

  return tokens;
}

function normalizeWeightName(name) {
  return String(name)
    .toLowerCase()
    .replace(/\bitalic\b/g, '')
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function parseTypographyWeight(value, fallbackName) {
  const normalized = normalizeWeightName(value || fallbackName);
  return TYPOGRAPHY_WEIGHT_BY_NAME[normalized];
}

function toTokenKey(name) {
  return String(name)
    .toLowerCase()
    .replace(/\bitalic\b/g, '')
    .replace(/[_\s]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}

function toScssString(value) {
  if (/^[-_a-zA-Z][-_a-zA-Z0-9]*$/.test(value)) {
    return value;
  }

  const escaped = value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  return `'${escaped}'`;
}

function toKebabCase(value) {
  return String(value)
    .toLowerCase()
    .replace(/[\s_]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}

function toRem(value, decimals = DEFAULT_REM_DECIMALS) {
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    throw new Error(`Expected a numeric value for rem conversion, received: ${String(value)}`);
  }

  const rem = value / 16;
  const fixed = rem.toFixed(decimals);
  const normalized = fixed.replace(/\.0+$/, '').replace(/(\.\d*?)0+$/, '$1');

  return `${normalized}rem`;
}

function toVariableFontName(fontName) {
  const trimmed = fontName.trim();

  if (trimmed.toLowerCase().endsWith(VARIABLE_FONT_SUFFIX.toLowerCase())) {
    return trimmed;
  }

  return `${trimmed}${VARIABLE_FONT_SUFFIX}`;
}

function normalizeComparableFontFamily(fontName) {
  return fontName
    .trim()
    .replace(new RegExp(`${VARIABLE_FONT_SUFFIX}$`, 'i'), '')
    .trim()
    .toLowerCase();
}

function shouldUseVariableFont(fontName, typography, options) {
  const normalizedFontName = normalizeComparableFontFamily(fontName);
  const normalizedPlainFamily = normalizeComparableFontFamily(typography.plainFamily);
  const normalizedBrandFamily = normalizeComparableFontFamily(typography.brandFamily);

  return (
    (options.plainVariable && normalizedFontName === normalizedPlainFamily) ||
    (options.brandVariable && normalizedFontName === normalizedBrandFamily)
  );
}

function parseTypography(tokens, options = {}) {
  const staticTokens = tokens.Static;
  const plainFamily = staticTokens?.Font?.Plain?.$value;
  const brandFamily = staticTokens?.Font?.Brand?.$value;

  if (typeof plainFamily !== 'string' || plainFamily.trim().length === 0) {
    throw new Error('Missing required token: Static.Font.Plain.$value');
  }

  if (typeof brandFamily !== 'string' || brandFamily.trim().length === 0) {
    throw new Error('Missing required token: Static.Font.Brand.$value');
  }

  const weights = {};
  const weightGroup = staticTokens?.Weight;

  if (!weightGroup || typeof weightGroup !== 'object') {
    throw new Error('Missing required token group: Static.Weight');
  }

  for (const [key, token] of Object.entries(weightGroup)) {
    const tokenName = token?.$value;
    const weight = parseTypographyWeight(tokenName, key);

    if (typeof weight !== 'number') {
      throw new Error(`Unsupported typography weight name: ${String(tokenName ?? key)}`);
    }

    weights[toTokenKey(key)] = weight;
  }

  return {
    plainFamily: options.plainVariable ? toVariableFontName(plainFamily) : plainFamily.trim(),
    brandFamily: options.brandVariable ? toVariableFontName(brandFamily) : brandFamily.trim(),
    weights,
  };
}

function parseTypescaleOverrides(tokens, typography, options = {}) {
  const staticTokens = tokens.Static;

  if (!staticTokens || typeof staticTokens !== 'object') {
    throw new Error('Missing required token group: Static');
  }

  const overrides = [];

  for (const [rawStyleName, styleTokens] of Object.entries(staticTokens)) {
    if (!styleTokens || typeof styleTokens !== 'object') {
      continue;
    }

    const font = styleTokens.Font?.$value;
    const weightName = styleTokens.Weight?.$value;
    const size = styleTokens.Size?.$value;
    const lineHeight = styleTokens['Line height']?.$value;
    const tracking = styleTokens.Tracking?.$value;

    if (
      typeof font !== 'string' ||
      typeof weightName !== 'string' ||
      typeof size !== 'number' ||
      typeof lineHeight !== 'number' ||
      typeof tracking !== 'number'
    ) {
      continue;
    }

    const styleName = toKebabCase(rawStyleName);
    const weight = parseTypographyWeight(weightName, rawStyleName);

    if (typeof weight !== 'number') {
      throw new Error(`Unsupported typography weight name in typescale: ${String(weightName)}`);
    }

    const style = {
      name: styleName,
      font: shouldUseVariableFont(font, typography, options) ? toVariableFontName(font) : font.trim(),
      weight,
      size: toRem(size),
      lineHeight: toRem(lineHeight),
      tracking: toRem(tracking),
    };

    const prominentWeightName = styleTokens['Weight-emphasized']?.$value;
    if (typeof prominentWeightName === 'string') {
      const prominentWeight = parseTypographyWeight(prominentWeightName, `${rawStyleName} Weight-emphasized`);
      if (typeof prominentWeight !== 'number') {
        throw new Error(`Unsupported typography emphasized weight name in typescale: ${String(prominentWeightName)}`);
      }
      style.prominentWeight = prominentWeight;
    }

    overrides.push(style);
  }

  if (overrides.length === 0) {
    throw new Error('No valid typescale styles were found in the provided typescale tokens file.');
  }

  const overridesByStyle = new Map(overrides.map((style) => [style.name, style]));
  const orderedOverrides = MATERIAL_TYPESCALE_STYLE_ORDER.map((styleName) => overridesByStyle.get(styleName)).filter(
    Boolean,
  );

  if (orderedOverrides.length === 0) {
    throw new Error('No Material typescale styles were found in the provided typescale tokens file.');
  }

  return orderedOverrides;
}

function typographyToScssMap(typography) {
  const lines = [];
  lines.push('(');
  lines.push(`${INDENT}plain-family: ${toScssString(typography.plainFamily)},`);
  lines.push(`${INDENT}brand-family: ${toScssString(typography.brandFamily)},`);

  for (const [name, value] of Object.entries(typography.weights)) {
    lines.push(`${INDENT}${name}-weight: ${value},`);
  }

  lines.push(')');
  return lines.join('\n');
}

function typographyOverridesToScssMap(overrides) {
  const lines = [];
  lines.push('(');

  for (const style of overrides) {
    const font = toScssString(style.font);
    lines.push(`${INDENT}${style.name}: ${style.weight} ${style.size} #{'/'} ${style.lineHeight} ${font},`);
    lines.push(`${INDENT}${style.name}-font: ${font},`);
    lines.push(`${INDENT}${style.name}-line-height: ${style.lineHeight},`);
    lines.push(`${INDENT}${style.name}-size: ${style.size},`);
    lines.push(`${INDENT}${style.name}-tracking: ${style.tracking},`);
    lines.push(`${INDENT}${style.name}-weight: ${style.weight},`);

    if (PROMINENT_WIEGHT_TYPESCALES.includes(style.name) && typeof style.prominentWeight === 'number') {
      lines.push(`${INDENT}${style.name}-weight-prominent: ${style.prominentWeight},`);
    }
  }

  lines.push(')');
  return lines.join('\n');
}

function buildScss(inputs, typography, typographyOverrides) {
  const typographyMap = typographyToScssMap(typography);
  const typographyOverridesMap = typographyOverridesToScssMap(typographyOverrides);

  return [
    SCSS_BANNER,
    '',
    `// Note: Typography tokens are generated from '${inputs.typography}'`,
    `$typography: ${typographyMap};`,
    '',
    `// Note: Typography overrides are generated from '${inputs.typescale}'`,
    `$typography-overrides: ${typographyOverridesMap};`,
    '',
  ].join('\n');
}

async function run(input, typescale, options) {
  const inputPath = path.resolve(input);
  const typescalePath = path.resolve(typescale);
  const outputPath = resolveOutputPath(inputPath, options);
  const tokens = await readTokens(inputPath);
  const typescaleTokens = await readTokens(typescalePath);
  const typography = parseTypography(tokens, options);
  const typographyOverrides = parseTypescaleOverrides(typescaleTokens, typography, options);
  const scss = buildScss(
    {
      typography: input,
      typescale: typescale,
    },
    typography,
    typographyOverrides,
  );

  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, scss, 'utf8');
}

async function main() {
  const program = new Command()
    .name('generate-typography-scss')
    .description('Generate typography SCSS from a typography tokens JSON file.')
    .argument('<input>', 'Path to the source tokens JSON file')
    .argument('<typescale>', 'Path to the source typescale tokens JSON file')
    .option('-o, --output <file>', 'Path to the output SCSS file')
    .option('--plain-variable', 'Turn plain font family into variable font name')
    .option('--brand-variable', 'Turn brand font family into variable font name')
    .action(run);

  try {
    await program.parseAsync();
  } catch (error) {
    // eslint-disable-next-line no-console
    console.error(`Error: ${error.message}`);
    process.exit(1);
  }
}

await main();
