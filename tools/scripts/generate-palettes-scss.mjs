#!/usr/bin/env node

import { Command } from 'commander';
import fs from 'node:fs/promises';
import path from 'node:path';

const PALETTES = ['primary', 'secondary', 'tertiary', 'neutral', 'neutral-variant', 'error'];
const TONES = [0, 10, 20, 25, 30, 35, 40, 50, 60, 70, 80, 90, 95, 98, 99, 100];
const EXTRA_TONES = [4, 6, 12, 17, 22, 24, 87, 92, 94, 96];
const PALETTE_BY_TOKEN = {
  Primary: 'primary',
  Secondary: 'secondary',
  Tertiary: 'tertiary',
  Neutral: 'neutral',
  'Neutral Variant': 'neutral-variant',
  Error: 'error',
};
const TONES_BY_PALETTE = {
  primary: TONES,
  secondary: TONES,
  tertiary: TONES,
  neutral: [...TONES, ...EXTRA_TONES],
  'neutral-variant': TONES,
  error: TONES,
};

const PALETTE_TOKEN_REGEX = /^(Primary|Secondary|Tertiary|Neutral|Neutral Variant|Error)\s+(\d+)$/;
const HEX_COLOR_REGEX = /^#[0-9a-fA-F]{6}$/;

const INDENT = '  ';
const SCSS_BANNER = `// This file was generated by running 'node tools/scripts/generate-palettes-scss.mjs'.
// Proceed with caution if making changes to this file.`;
const SCSS_EXPORTS = `$_rest: (
  secondary: map.get($_palettes, secondary),
  neutral: map.get($_palettes, neutral),
  neutral-variant: map.get($_palettes, neutral-variant),
  error: map.get($_palettes, error),
);

$primary-palette: map.merge(map.get($_palettes, primary), $_rest);
$tertiary-palette: map.merge(map.get($_palettes, tertiary), $_rest);
`;

function resolveOutputPath(inputPath, options) {
  if (options.output) {
    return path.resolve(options.output);
  }

  return path.format({
    dir: path.dirname(inputPath),
    name: path.basename(inputPath).replace(/(\.tokens)?\.json$/i, ''),
    ext: '.palettes.scss',
  });
}

async function readTokens(inputPath) {
  const raw = await fs.readFile(inputPath, 'utf8');
  const tokens = JSON.parse(raw);
  if (!tokens || typeof tokens !== 'object') {
    throw new Error('Input file must contain a JSON object.');
  } else if (!tokens.Palettes || typeof tokens.Palettes !== 'object') {
    throw new Error('Input file must contain a "Palettes" object.');
  }

  return tokens;
}

function parseTokens(tokens) {
  const palettes = {};

  for (const [key, value] of Object.entries(tokens.Palettes)) {
    const match = PALETTE_TOKEN_REGEX.exec(key);
    if (!match) {
      continue;
    }

    const token = match[1];
    if (!(token in PALETTE_BY_TOKEN)) {
      continue;
    }

    const paletteKey = PALETTE_BY_TOKEN[token];
    const tone = parseInt(match[2], 10);
    const hex = value?.$value?.hex.toLowerCase();

    palettes[paletteKey] ??= {};
    palettes[paletteKey][tone] = hex;
  }

  return palettes;
}

function validatePalettes(palettes) {
  const missing = [];
  const invalid = [];

  for (const key of PALETTES) {
    const tones = TONES_BY_PALETTE[key];
    const palette = palettes[key] ?? {};

    for (const tone of tones) {
      if (!(tone in palette)) {
        missing.push(`${key} ${tone}`);
      } else if (!HEX_COLOR_REGEX.test(palette[tone])) {
        invalid.push(`${key} ${tone}`);
      }
    }
  }

  const errors = [];
  if (missing.length > 0) {
    errors.push(`Missing palette entries (${missing.length}): ${missing.join(', ')}`);
  }
  if (invalid.length > 0) {
    errors.push(`Invalid hex color entries (${invalid.length}): ${invalid.join(', ')}`);
  }

  if (errors.length > 0) {
    throw new Error(errors.join('\n'));
  }
}

function palettesToScssMap(palettes) {
  const lines = [];
  lines.push('(');

  for (const key of PALETTES) {
    const tones = TONES_BY_PALETTE[key];
    const palette = palettes[key];
    lines.push(`${INDENT}${key}: (`);

    for (const tone of tones) {
      lines.push(`${INDENT}${INDENT}${tone}: ${palette[tone]},`);
    }

    lines.push(`${INDENT}),`);
  }

  lines.push(')');

  return lines.join('\n');
}

function buildScss(input, palettes) {
  const palettesScssMap = palettesToScssMap(palettes);
  const lines = [
    SCSS_BANNER,
    '',
    `@use 'sass:map';`,
    '',
    `// Note: Color palettes are generated from '${input}'`,
    `$_palettes: ${palettesScssMap};`,
    '',
    SCSS_EXPORTS,
  ];

  return lines.join('\n');
}

async function run2(input, options) {
  const inputPath = path.resolve(input);
  const outputPath = resolveOutputPath(inputPath, options);
  const tokens = await readTokens(inputPath);
  const palettes = parseTokens(tokens);

  validatePalettes(palettes);

  const scss = buildScss(input, palettes);

  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, scss, 'utf8');
}

async function main() {
  const program = new Command()
    .name('generate-palettes-scss')
    .description('Generate palettes.scss from a tonal tokens JSON file.')
    .argument('<input>', 'Path to the source tokens JSON file')
    .option('-o, --output <file>', 'Path to the output SCSS file')
    .action(run2);

  try {
    await program.parseAsync();
  } catch (error) {
    // eslint-disable-next-line no-console
    console.error(`Error: ${error.message}`);
    process.exit(1);
  }
}

await main();
